const root = document.querySelector(".brochure");
const langButtons = document.querySelectorAll("[data-lang-button]");
const textNodes = document.querySelectorAll("[data-i18n]");
const listNodes = document.querySelectorAll("[data-list]");

function createChecklist(items) {
  return items.map((item) => `<li>${item}</li>`).join("");
}

function createProcess(items) {
  return items
    .map(
      (item, index) => `
        <article class="process-step">
          <span class="process-number">${String(index + 1).padStart(2, "0")}</span>
          <h3>${item.title}</h3>
          <p>${item.text}</p>
        </article>
      `,
    )
    .join("");
}

function setLanguage(language) {
  const copy = brochureCopy[language] || brochureCopy.en;
  document.documentElement.lang = language;
  root.dataset.lang = language;

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) {
      node.textContent = copy[key];
    }
  });

  listNodes.forEach((node) => {
    const key = node.dataset.list;
    const items = copy.lists[key];
    if (!items) return;

    node.innerHTML = key === "process" ? createProcess(items) : createChecklist(items);
  });

  langButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.langButton === language);
  });

  localStorage.setItem("sarvesh-brochure-language", language);
}

langButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.langButton));
});

document.querySelector("[data-print]").addEventListener("click", () => {
  window.print();
});

const queryLanguage = new URLSearchParams(window.location.search).get("lang");
const initialLanguage = ["en", "de"].includes(queryLanguage)
  ? queryLanguage
  : localStorage.getItem("sarvesh-brochure-language") || "en";

setLanguage(initialLanguage);
